/** 본문에서 뽑아낼 수 있는 용어 목록 (긴 것부터) */
export const GLOSSARY_TERMS = Object.keys(GLOSSARY).sort((a, b) => b.length - a.length);

/**
 * '합', '충'처럼 일상 단어에 섞이기 쉬운 한 글자 용어는
 * 한자 병기가 붙어 있을 때만 용어로 인식한다. (예: 종합·궁합 오탐 방지)
 */
const REQUIRES_HANJA = new Set(["합", "충"]);

const HANJA = "[\\u4e00-\\u9fff]+";

/** 용어 + 뒤따르는 한자 병기를 한 덩어리로 잡는 정규식 */
export function buildTermPattern(): RegExp {
  const parts = GLOSSARY_TERMS.map((t) =>
    REQUIRES_HANJA.has(t) ? `${t}\\(${HANJA}\\)` : `${t}(?:\\(${HANJA}\\))?`
  );
  return new RegExp(`(${parts.join("|")})`, "g");
}

/** 매칭된 덩어리에서 사전 키를 되찾는다 */
export function termKeyOf(matched: string): string | undefined {
  const bare = matched.replace(/\(.*\)$/, "");
  return GLOSSARY[bare] ? bare : undefined;
}
